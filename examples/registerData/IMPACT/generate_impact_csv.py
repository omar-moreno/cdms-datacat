import os
import pandas as pd

# Generates an oldFile,newFile csv for the impact data

# Path of the generated csv
output_path = './copyFiles/fileChecks/IMPACT.csv'
# Path of oldFile
# The files that need to be renamed are prefixed with "coincident_TES_PMT_"
oldfile_path = '/nfs/slac/g/supercdms/tf/northwestern/AnimalData/AR70/processing_coinc_v0701/'
# Path of newFile
newfile_path = '/gpfs/slac/staas/fs1/supercdms/data/CDMS/Animal/R70/Processed/Releases/ProdCoinc0701/Merged/'
# Site ID
ID = '27'
# Prefix of data files
prefix = 'coincident_TES_PMT_'
# Data file extension
ext = 'pkl'

# Generates the oldfile name
# def oldfile(tes):
